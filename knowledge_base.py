def calculate_quality_adjusted_rate(base_modal_price, moisture_pct, shelling_pct):
    """
    Calculates actual farmer payout per quintal based on APMC trader norms:
    - Ideal moisture: 8.0%. Above 8%, deduction of 1.2% per extra moisture point.
    - Ideal shelling outturn (గింజ దిగుబడి): 70%. Bonus/deduction of Rs 65 per % point above/below 70%.
    """
    moisture_diff = max(0.0, moisture_pct - 8.0)
    moisture_deduction = base_modal_price * (moisture_diff * 0.012)
    
    shelling_diff = shelling_pct - 70.0
    shelling_adjustment = shelling_diff * 65.0
    
    effective_rate = round(base_modal_price - moisture_deduction + shelling_adjustment, 2)
    return effective_rate, round(moisture_deduction, 2), round(shelling_adjustment, 2)
